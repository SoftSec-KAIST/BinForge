from binforge import config
from binforge.models import Project, find_files
from binforge.utils import execute_command, mkdir

import re
import os

from enum import Enum

class DepType(Enum):
    LIBRARY = "library"
    HEADER = "header"


def validate_configure_file(configure_file_path):
    # print("[*] Configure file path:", configure_file_path)
    with open(configure_file_path, 'r', encoding='utf-8', errors='ignore') as f:
        for i, line in enumerate(f):
            if i >= 100:
                break
            if line.startswith("# Generated by GNU Autoconf "):
                return True
    return False


def get_deps(configure_path, dep_type: DepType = DepType.LIBRARY):
    with open(configure_path, "r", encoding="utf-8", errors="ignore") as f:
        lines = f.readlines()

    if dep_type == DepType.HEADER:
        pattern = re.compile(r'\bac_cv_header_[a-zA-Z0-9_]+\b')
    else:
        pattern = re.compile(r'\bac_cv_lib_[a-zA-Z0-9_]+\b')

    matched_vars = set()

    for line in lines:
        matches = pattern.findall(line)
        matched_vars.update(matches)

    names = set()

    for var in matched_vars:
        if dep_type == DepType.HEADER:
            subpattern = r"ac_cv_header_(.+)"
        else:
            subpattern = r"ac_cv_lib_([^_]+)_.+"

        match = re.match(subpattern, var)
        if match:
            names.add(match.group(1).lower())

    return sorted(names)


def get_extra_deps(base_dir, dep_type: DepType = DepType.LIBRARY):
    dirs_with_lib = []

    for name in os.listdir(base_dir):
        dir_path = os.path.join(base_dir, name)
        if dep_type == dep_type.LIBRARY:
            lib_path = os.path.join(dir_path, "lib")
        else:
            lib_path = os.path.join(dir_path, "include")
        if os.path.isdir(dir_path) and os.path.isdir(lib_path):
            dirs_with_lib.append(name)

    return dirs_with_lib


def analyze_dependencies(project_list: list[Project]):
    for project in project_list:
        # print(f"\n{project.name}")
        assert project.source_path is not None, "project.source_path is None"
        assert project.full_name is not None, "project.full_name is None"
        source_code_root = os.path.join(project.source_path, project.full_name)

        #! is C project
        if not project.is_c_project():
            # print(f"Not a C project: {project.name}")
            continue

        source_code_root = os.path.join(project.source_path, project.full_name)

        ##! CMakefile
        use_cmake = False
        cmake_file_path = None
        result_find_cmakefile = find_files("CMakeLists.txt", source_code_root)
        if result_find_cmakefile:
            use_cmake = True
            cmake_file_path = result_find_cmakefile[0]

        # print(f"[*] use_cmake: {use_cmake}")
        # print(f"[*] cmake_file_path: {cmake_file_path}")
        project.use_cmake = use_cmake
        project.cmake_file_path = cmake_file_path

        ##! configure file
        use_configure = False
        use_valid_configure = False
        configure_file_path = None
        result_find_configure = find_files("configure", source_code_root)
        if result_find_configure:
            configure_file_path = result_find_configure[0]
            use_configure = True
            use_valid_configure = validate_configure_file(configure_file_path)

        # print(f"[*] use_configure: {use_configure}")
        # print(f"[*] use_valid_configure: {use_valid_configure}")
        # print(f"[*] configure_file_path: {configure_file_path}")
        project.use_configure = use_configure
        project.configure_file_path = configure_file_path

        # if not use_cmake and not use_configure:
        #     continue

        # valid_cmake = use_cmake
        # valid_configure = use_configure and use_valid_configure

    project_list = [p for p in project_list if p.use_configure]

    libs = []
    headers = []
    for project in project_list:
        dep_libs = get_deps(project.configure_file_path, dep_type=DepType.LIBRARY)
        libs.extend(dep_libs)
        project.dep_libs = dep_libs
        # print(dep_libs)

        dep_headers = get_deps(project.configure_file_path, dep_type=DepType.HEADER)
        dep_headers = [h.replace("_h", ".h") for h in dep_headers]
        headers.extend(dep_headers)
        project.dep_headers = dep_headers
        # print(dep_headers)

    libs = sorted(list(set(libs)))
    headers = sorted(list(set(headers)))

    work_dir = os.path.join("miniconf")
    mkdir(work_dir, exist_ok=True)
    with open(f"{work_dir}/configure.ac", "w") as f:
        f.write("AC_INIT([libcheck], [1.0])\n")
        f.write("AC_PROG_CC\n")
        for lib in libs:
            f.write(f"AC_CHECK_LIB([{lib}], [main])\n")
        for header in headers:
            f.write(f"AC_CHECK_HEADER([{header}])\n")
        f.write("AC_OUTPUT\n")

    cmd = "autoconf"
    execute_command(cmd, directory=work_dir, DEBUG_LEVEL=0)

    toolchain_path = os.path.join(config.TOOL_PATH, "gcc", "bootstrap")
    compiler_prefix = "x86_64-unknown-linux-gnu"

    cmd = ""
    cmd += f"export PATH={toolchain_path}/bin:$PATH;"
    cmd += f"./configure "
    cmd += f"  --build=x86_64-linux-gnu "
    cmd += f"  --host={compiler_prefix} "
    cmd += f"  CC=\"{compiler_prefix}-gcc\" "
    cmd += f"  CFLAGS=\""
    cmd += f"    -isysroot {toolchain_path}/{compiler_prefix}/sysroot"
    cmd += f"    -I{toolchain_path}/{compiler_prefix}/sysroot/usr/include"

    base_dir = os.path.join(config.EXTRA_DEP_PATH, "install", "x86_64")
    installed_deps = get_extra_deps(base_dir, dep_type=DepType.HEADER)
    for dep in installed_deps:
        cmd += f"    -I{config.EXTRA_DEP_PATH}/install/x86_64/{dep}/include"

    cmd += f"   \""
    cmd += f"  LDFLAGS=\""
    cmd += f"    -L{toolchain_path}/{compiler_prefix}/lib"

    base_dir = os.path.join(config.EXTRA_DEP_PATH, "install", "x86_64")
    installed_deps = get_extra_deps(base_dir, dep_type=DepType.LIBRARY)
    for dep in installed_deps:
        cmd += f"    -L{config.EXTRA_DEP_PATH}/install/x86_64/{dep}/lib"
    cmd += f"   \""

    cmd += f"  AR=\"{compiler_prefix}-ar\""
    cmd += f"  RANLIB=\"{compiler_prefix}-ranlib\""
    cmd += f"  NM=\"{compiler_prefix}-nm\""

    cmd_result = execute_command(cmd, directory=work_dir, DEBUG_LEVEL=0)
    configure_output = cmd_result.stdout

    lib_pattern = re.compile(r"checking for main in -l(\w+)\.\.\.\s*(yes|no)")
    header_pattern = re.compile(r"checking for (.+)\.\.\.\s*(yes|no)")

    result_libs = {}
    result_headers = {}

    for line in configure_output.splitlines():
        m = lib_pattern.search(line)
        if m:
            lib = m.group(1)
            status = m.group(2) == "yes"
            result_libs[lib] = status
        else:
            h = header_pattern.search(line)
            if h:
                header = h.group(1).strip()
                status = h.group(2) == "yes"
                if header.endswith(".h"):
                    result_headers[header] = status

    print("Libraries:")
    for lib, ok in sorted(result_libs.items(), key=lambda x: (not x[1], x[0])):
        print(f"{lib:15}: {'FOUND' if ok else 'MISSING'}")

    print("\nHeaders:")
    for hdr, ok in sorted(result_headers.items(), key=lambda x: (not x[1], x[0])):
        print(f"{hdr:30}: {'FOUND' if ok else 'MISSING'}")

    missing_libs = [lib for lib, ok in result_libs.items() if not ok]
    missing_headers = [hdr for hdr, ok in result_headers.items() if not ok]

    print("\n==> MISSING Libraries required by which projects?")

    for lib in missing_libs:
        print(f"\nLibrary '{lib}' required by:")
        for project in project_list:
            if hasattr(project, "dep_libs") and lib in project.dep_libs:
                print(f"  - {project.name}")

    print("\n==> MISSING Headers required by which projects?")

    for hdr in missing_headers:
        print(f"\nHeader '{hdr}' required by:")
        for project in project_list:
            if hasattr(project, "dep_headers") and hdr in project.dep_headers:
                print(f"  - {project.name}")

    # Cleanup
    execute_command(f"rm -rf {work_dir}", DEBUG_LEVEL=0)

