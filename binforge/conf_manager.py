PROJECT_COLUMN_WIDTH = 25


def find_primary_file(file_name: str, source_code_root: str) -> str | None:
    candidates = find_files(file_name, source_code_root)
    if not candidates:
        return None

    def sort_key(path: str) -> tuple[int, str]:
        rel_path = os.path.relpath(path, source_code_root)
        return rel_path.count(os.sep), rel_path

    candidates.sort(key=sort_key)
    return candidates[0]


def is_autoconf_generated_configure_file(configure_file_path: str) -> bool:
    with open(configure_file_path, 'r', encoding='utf-8', errors='ignore') as f:
        for i, line in enumerate(f):
            if i >= 100:
                break
            if line.startswith("# Generated by Autoconf ") or line.startswith("# Generated by GNU Autoconf "):
                return True
    return False


def can_generate_configure_with_autoreconf(project: Project, source_code_root: str) -> bool:
    base_tmp = "/tmp/conf"
    os.makedirs(base_tmp, exist_ok=True)

    tmp_dir = tempfile.mkdtemp(prefix=f"{project.name}_", dir=base_tmp)

    try:
        shutil.copytree(
            source_code_root,
            tmp_dir,
            dirs_exist_ok=True,
            symlinks=True,
            ignore_dangling_symlinks=True
        )

        autoreconf_result = execute_command(
            "autoreconf -fvi 2>&1",
            directory=tmp_dir,
            DEBUG_LEVEL=-2,
            exit_on_error=False,
        )
        if autoreconf_result.returncode != 0:
            return False

        configure_file_path = find_primary_file("configure", tmp_dir)
        if configure_file_path:
            return is_autoconf_generated_configure_file(configure_file_path)
        return False
    finally:
        shutil.rmtree(tmp_dir, ignore_errors=True)


def find_stale_autotools_outputs(project: Project) -> list[tuple[Path, Path]]:
    """Return existing Autotools outputs older than their source inputs."""
    source_root = Path(project.source_path) / project.name
    stale: list[tuple[Path, Path]] = []

    for source_name in ("configure.ac", "configure.in"):
        for source in source_root.rglob(source_name):
            generated = source.parent / "configure"
            if (generated.is_file()
                    and source.stat().st_mtime_ns > generated.stat().st_mtime_ns):
                stale.append((source, generated))

    for source in source_root.rglob("Makefile.am"):
        generated = source.with_name("Makefile.in")
        if (generated.is_file()
                and source.stat().st_mtime_ns > generated.stat().st_mtime_ns):
            stale.append((source, generated))

    return stale


def _autoreconf_include_dirs(source_root: Path) -> list[str]:
    include_dirs = []
    for candidate in (source_root / "m4", source_root / "build" / "m4"):
        if candidate.is_dir():
            include_dirs.append(str(candidate.relative_to(source_root)))
    return include_dirs


@contextmanager
def regenerated_autotools_source(project: Project):
    """Yield an isolated project copy prepared with autoreconf, or None."""
    source_root = Path(project.source_path) / project.name
    if not source_root.is_dir():
        yield None
        return

    with tempfile.TemporaryDirectory(
        prefix=".binforge-autoreconf-",
        dir=project.source_path,
    ) as temporary:
        prepared_parent = Path(temporary)
        prepared_root = prepared_parent / project.name
        shutil.copytree(
            source_root,
            prepared_root,
            symlinks=True,
            ignore_dangling_symlinks=True,
        )

        command = ["autoreconf", "-fvi"]
        for include_dir in _autoreconf_include_dirs(prepared_root):
            command.extend(["-I", include_dir])

        result = execute_command(
            shlex.join(command) + " 2>&1",
            directory=str(prepared_root),
            DEBUG_LEVEL=0,
            exit_on_error=False,
        )

        os.makedirs(project.log_path, exist_ok=True)
        with open(
            os.path.join(project.log_path, f"{project.name}.autoreconf.log"),
            "w",
            encoding="utf-8",
        ) as log_file:
            if result.stdout:
                log_file.write(result.stdout)
                log_file.write("\n")
            if result.stderr:
                log_file.write(result.stderr)
                log_file.write("\n")

        configure_file_path = find_primary_file("configure", str(prepared_root))
        if result.returncode != 0 or not configure_file_path:
            yield None
            return

        prepared = deepcopy(project)
        prepared.source_path = str(prepared_parent)
        prepared.configure_file_path = configure_file_path
        prepared.invoke_autoreconf = False
        prepared.use_configure = True
        prepared.use_cmake = False
        yield prepared



def analyze_project(project: Project):
    has_cmakelist = False
    has_configure = False
    has_configure_ac = False
    has_configure_in = False
    has_autogenerated_configure = False

    cmake_file_path = None
    configure_file_path = None

    use_cmake = False
    use_configure = False
    invoke_autoreconf = False

    assert project.source_path is not None, "project.source_path is None"
    # assert project.full_name is not None, "project.full_name is None"

    source_code_root = os.path.join(project.source_path, project.name) or ''

    ##! CMake
    cmake_file_path = find_primary_file("CMakeLists.txt", source_code_root)
    if cmake_file_path:
        has_cmakelist = True

    ##! Autotools
    #! configure
    configure_file_path = find_primary_file("configure", source_code_root)
    if configure_file_path:
        has_configure = True
        has_autogenerated_configure = is_autoconf_generated_configure_file(configure_file_path)

    #! configure.ac or configure.in
    if find_files("configure.ac", source_code_root):
        has_configure_ac = True
    if find_files("configure.in", source_code_root):
        has_configure_in = True

    if not has_configure and (has_configure_ac or has_configure_in):
        invoke_autoreconf = can_generate_configure_with_autoreconf(project, source_code_root)

    if has_autogenerated_configure:
        use_configure = True

    if invoke_autoreconf:
        use_configure = True

    project.use_configure = use_configure
    project.use_cmake = has_cmakelist and not use_configure
    project.invoke_autoreconf = invoke_autoreconf

    use_cmake = project.use_cmake


    if project.use_configure:
        project.configure_file_path = configure_file_path
    elif project.use_cmake:
        project.cmake_file_path = cmake_file_path

    #! ==========================================

    row = []
    row.append(project.name)

    if has_cmakelist:
        row.append("O")
    else:
        row.append("X")

    if has_configure:
        row.append('O')
    else:
        row.append('X')

    if has_configure_ac or has_configure_in:
        row.append('O')
    else:
        row.append('X')

    if has_autogenerated_configure:
        row.append('O')
    else:
        row.append('X')

    if invoke_autoreconf:
        row.append('O')
    else:
        row.append('X')

    if use_configure:
        row.append('O')
    else:
        row.append('X')

    if use_cmake:
        row.append('O')
    else:
        row.append('X')

    if use_configure or use_cmake:
        row.append('O')
    else:
        row.append('X')

    return row


def analyze_projects(projects: list[Project], targets: list[str]=[]):
    if targets:
        _projects, projects = projects, []
        for proj in _projects:
            if proj.name in targets:
                projects.append(proj)

    tb = []
    for project in projects:
        row = analyze_project(project)

        tb.append(row)

    project_col_width = PROJECT_COLUMN_WIDTH
    hd = f"{'Project':<{project_col_width}} | hasCMake | hasConf | hasConf.ac | hasA.Conf | Autoreconf | Configure | CMake | InScope |"
    print(hd)
    print('-' * len(hd))
    for row in tb:
        print(f"{row[0]:<{project_col_width}} | {row[1]:<8} | {row[2]:<7} | {row[3]:<10} | {row[4]:<9} | {row[5]:<10} | {row[6]:<9} | {row[7]:<5} | {row[8]:<7} |")
    print()

    ret = []
    for row in tb:
        ret.append([row[6], row[7]])
    # print(ret)
    
    return ret

